using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Magnitudo.Analyzers;

/// <summary>
///     Emits a <c>global using</c> alias for each quantity in the catalog, plus conversion methods.
/// </summary>
/// <remarks>
///     Each alias names the quantity's storage type, so it erases to a primitive at runtime. The generator sorts
///     aliases and conversions by name so the output is the same for the same catalog.
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class QuantityAliasGenerator : IIncrementalGenerator
{
    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<AdditionalText> catalogs = context.AdditionalTextsProvider
            .Where(file => file.Path.EndsWith(".magnitudo", StringComparison.OrdinalIgnoreCase));

        IncrementalValueProvider<ImmutableArray<ConversionHost>> hosts = context.SyntaxProvider
            .CreateSyntaxProvider(IsHostCandidate, GetHost)
            .Where(static host => host is not null)
            .Select(static (host, _) => host!)
            .Collect();

        context.RegisterSourceOutput(
            hosts.Combine(catalogs.Collect()),
            static (productionContext, input) =>
            {
                var (hostList, files) = input;
                var catalog = UnitCatalog.Parse(
                    files,
                    productionContext.CancellationToken,
                    productionContext.ReportDiagnostic);

                if (catalog.Definitions.Length == 0)
                    return;

                // A partial class can have several declarations. Keep the first one by file and position.
                var distinctHosts = hostList
                    .OrderBy(host => host.FullName, StringComparer.Ordinal)
                    .ThenBy(host => host.Location.GetLineSpan().Path, StringComparer.Ordinal)
                    .ThenBy(host => host.Location.SourceSpan.Start)
                    .GroupBy(host => host.FullName, StringComparer.Ordinal)
                    .Select(group => group.First())
                    .ToList();

                // The output uses "\n" only, so it is the same on every OS.
                var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
                foreach (var definition in catalog.Definitions.OrderBy(
                             item => item.Alias,
                             StringComparer.Ordinal))
                    source.Append("global using ").Append(definition.Alias).Append(" = ")
                        .Append(GetAliasTarget(definition.StorageType)).Append(";\n");

                // The default class exists only when the project declares no host, valid or not.
                if (distinctHosts.Count == 0 && catalog.Conversions.Length > 0)
                {
                    source.Append("\nnamespace Magnitudo.Generated\n{\n")
                        .Append("    /// <summary>\n")
                        .Append("    /// Catalog-generated conversions to and from the catalog's canonical units.\n")
                        .Append("    /// </summary>\n")
                        .Append("    internal static class UnitConversions\n    {\n");
                    AppendConversions(source, catalog.Conversions);
                    source.Append("    }\n}\n");
                }

                productionContext.AddSource(
                    "Magnitudo.QuantityAliases.g.cs",
                    SourceText.From(source.ToString(), Encoding.UTF8));

                foreach (var host in distinctHosts)
                {
                    if (host.IsInvalid)
                    {
                        productionContext.ReportDiagnostic(
                            Diagnostic.Create(Diagnostics.InvalidConversionClass, host.Location, host.FullName));
                        continue;
                    }

                    if (catalog.Conversions.Length == 0)
                        continue;

                    productionContext.AddSource(
                        GetHostHintName(host.FullName),
                        SourceText.From(GetHostSource(host, catalog.Conversions), Encoding.UTF8));
                }
            });
    }

    private static bool IsHostCandidate(SyntaxNode node, CancellationToken cancellationToken)
    {
        if (node is not ClassDeclarationSyntax declaration)
            return false;

        foreach (var list in declaration.AttributeLists)
        foreach (var attribute in list.Attributes)
        {
            string name = attribute.Name switch
            {
                QualifiedNameSyntax qualified => qualified.Right.Identifier.ValueText,
                AliasQualifiedNameSyntax aliased => aliased.Name.Identifier.ValueText,
                SimpleNameSyntax simple => simple.Identifier.ValueText,
                _ => string.Empty
            };

            if (name is "UnitConversions" or "UnitConversionsAttribute")
                return true;
        }

        return false;
    }

    private static ConversionHost? GetHost(GeneratorSyntaxContext context, CancellationToken cancellationToken)
    {
        var declaration = (ClassDeclarationSyntax)context.Node;
        if (context.SemanticModel.GetDeclaredSymbol(declaration, cancellationToken) is not { } symbol)
            return null;

        bool marked = symbol.GetAttributes().Any(attribute =>
            attribute.AttributeClass?.ToDisplayString() == "Magnitudo.UnitConversionsAttribute");
        if (!marked)
            return null;

        bool allPartial = symbol.DeclaringSyntaxReferences
            .Select(reference => reference.GetSyntax(cancellationToken))
            .OfType<ClassDeclarationSyntax>()
            .All(item => item.Modifiers.Any(SyntaxKind.PartialKeyword));

        bool isInvalid = !symbol.IsStatic || !allPartial || symbol.Arity > 0 || symbol.ContainingType is not null;

        string? ns = symbol.ContainingNamespace.IsGlobalNamespace
            ? null
            : symbol.ContainingNamespace.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat);

        return new ConversionHost(
            ns,
            symbol.Name,
            symbol.ToDisplayString(),
            isInvalid,
            declaration.Identifier.GetLocation());
    }

    private static string GetHostHintName(string fullName)
    {
        var name = new StringBuilder("Magnitudo.UnitConversions.");
        foreach (char c in fullName)
            name.Append(char.IsLetterOrDigit(c) || c is '.' or '_' ? c : '_');
        return name.Append(".g.cs").ToString();
    }

    private static string GetHostSource(ConversionHost host, ImmutableArray<UnitConversionDefinition> conversions)
    {
        string className = SyntaxFacts.GetKeywordKind(host.Name) != SyntaxKind.None ? "@" + host.Name : host.Name;
        string indent = host.Namespace is null ? string.Empty : "    ";

        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n\n");
        if (host.Namespace is not null)
            source.Append("namespace ").Append(host.Namespace).Append("\n{\n");

        source.Append(indent).Append("static partial class ").Append(className).Append('\n')
            .Append(indent).Append("{\n");
        AppendConversions(source, conversions, indent);
        source.Append(indent).Append("}\n");

        if (host.Namespace is not null)
            source.Append("}\n");

        return source.ToString();
    }

    /// <summary>
    ///     Appends the documented <c>From</c> and <c>To</c> methods for every conversion.
    /// </summary>
    /// <remarks>
    ///     The methods are public and the class decides who sees them. Each method has a summary, a parameter, and a
    ///     return description so a public host builds clean under <c>GenerateDocumentationFile</c>.
    /// </remarks>
    private static void AppendConversions(
        StringBuilder source, ImmutableArray<UnitConversionDefinition> conversions, string classIndent = "")
    {
        string pad = classIndent + "        ";
        foreach (var conversion in conversions.OrderBy(item => item.UnitName, StringComparer.Ordinal))
        {
            string type = GetAliasTarget(conversion.StorageType);
            string scale = GetLiteral(conversion.Scale, conversion.StorageType);
            string offset = GetLiteral(conversion.Offset, conversion.StorageType);
            source
                .Append(pad).Append("/// <summary>\n")
                .Append(pad).Append("/// Converts a value in ").Append(conversion.UnitName)
                .Append(" to the canonical unit of the '").Append(conversion.QuantityId).Append("' quantity.\n")
                .Append(pad).Append("/// </summary>\n")
                .Append(pad).Append("/// <param name=\"value\">The value in ").Append(conversion.UnitName).Append(".</param>\n")
                .Append(pad).Append("/// <returns>The value in the canonical unit.</returns>\n")
                .Append(pad).Append("[return: global::Magnitudo.QuantityAttribute(\"")
                .Append(conversion.QuantityId).Append("\")]\n")
                .Append(pad).Append("public static ").Append(type)
                .Append(" From").Append(conversion.UnitName).Append('(')
                .Append(type).Append(" value) => value * ")
                .Append(scale).Append(" + ").Append(offset).Append(";\n\n")
                .Append(pad).Append("/// <summary>\n")
                .Append(pad).Append("/// Converts a value in the canonical unit of the '").Append(conversion.QuantityId)
                .Append("' quantity to ").Append(conversion.UnitName).Append(".\n")
                .Append(pad).Append("/// </summary>\n")
                .Append(pad).Append("/// <param name=\"value\">The value in the canonical unit.</param>\n")
                .Append(pad).Append("/// <returns>The value in ").Append(conversion.UnitName).Append(".</returns>\n")
                .Append(pad).Append("public static ").Append(type)
                .Append(" To").Append(conversion.UnitName)
                .Append("([global::Magnitudo.QuantityAttribute(\"")
                .Append(conversion.QuantityId).Append("\")] ")
                .Append(type).Append(" value) => (value - ")
                .Append(offset).Append(") / ").Append(scale).Append(";\n\n");
        }
    }

    /// <summary>
    ///     A class marked <c>[UnitConversions]</c>, in a form that compares by value.
    /// </summary>
    /// <remarks>
    ///     Value equality lets the incremental pipeline skip work when an edit leaves the host unchanged.
    /// </remarks>
    private sealed class ConversionHost : IEquatable<ConversionHost>
    {
        internal ConversionHost(string? ns, string name, string fullName, bool isInvalid, Location location)
        {
            Namespace = ns;
            Name = name;
            FullName = fullName;
            IsInvalid = isInvalid;
            Location = location;
        }

        internal string? Namespace { get; }

        internal string Name { get; }

        internal string FullName { get; }

        /// <summary>
        ///     Gets a value that says the class is not static, partial, non-generic, and top-level.
        /// </summary>
        internal bool IsInvalid { get; }

        internal Location Location { get; }

        public bool Equals(ConversionHost? other)
        {
            return other is not null &&
                   Namespace == other.Namespace &&
                   Name == other.Name &&
                   FullName == other.FullName &&
                   IsInvalid == other.IsInvalid &&
                   Location.Equals(other.Location);
        }

        public override bool Equals(object? obj)
        {
            return Equals(obj as ConversionHost);
        }

        public override int GetHashCode()
        {
            return StringComparer.Ordinal.GetHashCode(FullName);
        }
    }

    /// <summary>
    ///     Returns the type name to use as the target of a <c>global using</c> alias.
    /// </summary>
    /// <remarks>
    ///     Before C# 12, a <c>using</c> alias cannot name a keyword type such as <c>float</c>, <c>string</c>, or
    ///     <c>object</c>, and it cannot name <c>T?</c>. The generator maps each keyword to its <c>global::System</c>
    ///     type and <c>T?</c> to <see cref="Nullable{T}" /> so the aliases compile on C# 10 and C# 11. A nullable
    ///     reference type such as <c>string?</c> loses the annotation, because an alias cannot carry one. Other
    ///     names pass through unchanged. The catalog parser rejects <c>nint</c> and <c>nuint</c> before this
    ///     method runs.
    /// </remarks>
    private static string GetAliasTarget(string storageType)
    {
        storageType = storageType.Trim();
        bool nullable = storageType.EndsWith("?", StringComparison.Ordinal);
        string inner = nullable ? storageType.Substring(0, storageType.Length - 1).Trim() : storageType;

        string? target = StorageTypes.GetKeyword(inner) switch
        {
            "bool" => "global::System.Boolean",
            "byte" => "global::System.Byte",
            "sbyte" => "global::System.SByte",
            "short" => "global::System.Int16",
            "ushort" => "global::System.UInt16",
            "int" => "global::System.Int32",
            "uint" => "global::System.UInt32",
            "long" => "global::System.Int64",
            "ulong" => "global::System.UInt64",
            "float" => "global::System.Single",
            "double" => "global::System.Double",
            "decimal" => "global::System.Decimal",
            "char" => "global::System.Char",
            "string" => "global::System.String",
            "object" => "global::System.Object",
            _ => null
        };

        if (target is null)
            return storageType;

        bool isReferenceType = target is "global::System.String" or "global::System.Object";
        return nullable && !isReferenceType ? "global::System.Nullable<" + target + ">" : target;
    }

    /// <summary>
    ///     Formats <paramref name="value" /> as a C# literal that matches <paramref name="storageType" />.
    /// </summary>
    /// <remarks>
    ///     The catalog parser accepts only <c>float</c>, <c>double</c>, and <c>decimal</c> here. Double storage gets a
    ///     <c>d</c> suffix.
    /// </remarks>
    private static string GetLiteral(double value, string storageType)
    {
        string text = StorageTypes.FormatNumber(value);
        return StorageTypes.GetKeyword(storageType) switch
        {
            "float" => text + "f",
            "decimal" => text + "m",
            _ => text + "d"
        };
    }
}
